package UD5_POO_ClasesYObjetos.Relacion9_Clases.Ejercicio3;

public class Animal {
    //Atributos
    int cantPatas;
    boolean patas;
    String especie;

    //Metodos
    public int getCantPatas() {
        return cantPatas;
    }
    public void setCantPatas(int cantPatas) {
        this.cantPatas = cantPatas;
    }
    public boolean isPatas() {
        return patas;
    }
    public void setPatas(boolean patas) {
        this.patas = patas;
    }
    public String getEspecie() {
        return especie;
    }
    public void setEspecie(String especie) {
        this.especie = especie;
    }

    
}
